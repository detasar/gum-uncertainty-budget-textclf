"""Assemble the publishable repo folder (repo/) with the same flat layout the scripts expect, and write MANIFEST.json (sha256 of every file).
Embedding caches (cache/emb_*.npz, ~40 MB) are regenerated by embed_box.py / mac/embed_gemma.py and are not committed."""
import json, os, shutil, hashlib, glob
H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, "repo")
for d in ["src", "data", "results", "figures"]:
    shutil.rmtree(os.path.join(R, d), ignore_errors=True)
def cp(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy2(src, dst)
for f in ["common.py", "prep_data.py", "embed_box.py", "budget.py", "repeatability.py", "plots.py", "gen_tables.py", "make_repo.py",
          "results.json", "repeatability.json", "raw_supervised_probs.npz", "tables.md", "lit-review.md", "manifest_meta.json"]:
    if os.path.exists(f"{H}/{f}"): cp(f"{H}/{f}", f"{R}/{f}")
cp(f"{H}/experiment.md", f"{R}/EXPERIMENT.md")
for f in glob.glob(f"{H}/*.png"): cp(f, f"{R}/{os.path.basename(f)}")
for f in glob.glob(f"{H}/mac_scripts/*"): cp(f, f"{R}/mac/{os.path.basename(f)}")
for f in ["supervised_set.json", "zs_set.json"]: cp(f"{H}/cache/{f}", f"{R}/cache/{f}")
for f in glob.glob(f"{H}/cache/mac/*.jsonl"): cp(f, f"{R}/cache/mac/{os.path.basename(f)}")
for f in glob.glob(f"{H}/cache/mac/logs/*.log"): cp(f, f"{R}/cache/mac/logs/{os.path.basename(f)}")
META = json.load(open(f"{H}/manifest_meta.json"))
files = {}
for root, _, fs in os.walk(R):
    for f in fs:
        p = os.path.join(root, f); rel = os.path.relpath(p, R)
        if rel == "MANIFEST.json" or rel.startswith("cache/emb_"): continue
        files[rel] = {"bytes": os.path.getsize(p), "sha256": hashlib.sha256(open(p, "rb").read()).hexdigest()}
META["files"] = dict(sorted(files.items()))
json.dump(META, open(f"{R}/MANIFEST.json", "w"), indent=2)
print(len(files), "files in manifest")
